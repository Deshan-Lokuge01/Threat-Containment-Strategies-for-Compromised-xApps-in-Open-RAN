%RUN_ALL  Regenerate every ZT-XGuard scalability figure from the bundled CSVs.
% Usage (on a machine with MATLAB):
%   cd scalability_matlab_package
%   run_all
% Produces PDF (vector) + PNG (200 dpi) for each figure in this same folder.
% Every fig_*.m is self-contained: it reads its CSV via a path relative to the
% script, so this works regardless of the current working directory.

here=fileparts(mfilename('fullpath')); cd(here);
fprintf('ZT-XGuard scalability figures -> %s\n\n',here);

figs={ ...
  @fig_exp1_detector,        'Exp1  detector cycle latency vs N'; ...
  @fig_exp1_resource,        'Exp1  detector CPU + RSS vs N'; ...
  @fig_exp1_latency_dist,    'Exp1  cycle-latency distribution vs N (raw)'; ...
  @fig_exp2_saturation,      'Exp2  offered vs achieved throughput'; ...
  @fig_exp2_latency,         'Exp2  service p50/p95/p99 latency'; ...
  @fig_exp2_deadline_miss,   'Exp2  1s deadline-miss %'; ...
  @fig_exp3_fourlock,        'Exp3  per-stage latency vs K'; ...
  @fig_exp3_makespan_boxplot,'Exp3  containment makespan boxplot'; ...
  @fig_exp3_nontarget,       'Exp3  non-target correctness'};

for i=1:size(figs,1)
    fprintf('[%d/%d] %s ... ',i,size(figs,1),figs{i,2});
    try, figs{i,1}(); fprintf('ok\n'); catch e, fprintf('FAILED: %s\n',e.message); end
end
fprintf('\nDone. PDFs/PNGs written next to the .m files.\n');
